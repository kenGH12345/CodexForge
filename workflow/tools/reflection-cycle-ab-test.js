#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const { isReflectionCycleEnabled } = require('../core/reflection-cycle');

const DEFAULT_RUNS = 3;
const CONFIG_PATH = 'workflow.config.js';

function readConfig(projectRoot) {
  return require(path.resolve(projectRoot, CONFIG_PATH));
}

function writeConfig(projectRoot, config) {
  const content = `// Auto-generated by reflection-cycle-ab-test.js\nmodule.exports = ${JSON.stringify(config, null, 2)};\n`;
  fs.writeFileSync(path.resolve(projectRoot, CONFIG_PATH), content, 'utf-8');
}

function setEnabled(projectRoot, enabled) {
  const config = readConfig(projectRoot);
  if (!config.reflectionCycle) config.reflectionCycle = {};
  config.reflectionCycle.enabled = enabled;
  writeConfig(projectRoot, config);
}

function restoreConfig(projectRoot, originalConfig) {
  writeConfig(projectRoot, originalConfig);
}

async function runSingleTest(projectRoot, label) {
  const startTime = Date.now();
  const metrics = {
    label,
    startTime: new Date().toISOString(),
    durationMs: 0,
    signalsGenerated: 0,
    actionsGenerated: 0,
    converged: false,
    errorCount: 0,
    errors: [],
  };

  try {
    const { ReflectionCycle } = require('../core/reflection-cycle');
    const cycle = new ReflectionCycle({ projectRoot, verbose: false });

    const testSignals = [
      { type: 'TEST_FAILURE', source: 'ab-test', severity: 'MEDIUM', timestamp: new Date().toISOString(), context: { test: 'reflection-cycle-ab-test', message: 'Synthetic test failure for baseline measurement' } },
      { type: 'USER_FEEDBACK', source: 'ab-test', severity: 'LOW', timestamp: new Date().toISOString(), context: { test: 'reflection-cycle-ab-test', message: 'Synthetic user feedback for baseline measurement' } },
    ];

    const result = await cycle.runCycle(testSignals);

    metrics.signalsGenerated = testSignals.length;
    metrics.actionsGenerated = result?.actions?.length ?? 0;
    metrics.converged = result?.converged ?? false;
    metrics.rounds = result?.rounds ?? 0;
  } catch (err) {
    metrics.errorCount++;
    metrics.errors.push(err.message);
  }

  metrics.durationMs = Date.now() - startTime;
  metrics.endTime = new Date().toISOString();
  return metrics;
}

async function runAblationTest(projectRoot, runs) {
  const originalConfig = readConfig(projectRoot);
  const originalEnabled = originalConfig.reflectionCycle?.enabled ?? true;

  const results = { enabled: [], disabled: [], comparison: null };

  console.log(`\n🔬 ReflectionCycle A/B Ablation Test`);
  console.log(`   Project: ${projectRoot}`);
  console.log(`   Runs per config: ${runs}`);
  console.log(`   Original config: reflectionCycle.enabled = ${originalEnabled}\n`);

  // Phase 1: Run with enabled=true
  console.log(`📊 Phase 1: Running with reflectionCycle.enabled = true`);
  setEnabled(projectRoot, true);
  delete require.cache[require.resolve(path.resolve(projectRoot, CONFIG_PATH))];
  delete require.cache[require.resolve('../core/reflection-cycle')];

  for (let i = 0; i < runs; i++) {
    console.log(`   Run ${i + 1}/${runs}...`);
    const m = await runSingleTest(projectRoot, 'enabled');
    results.enabled.push(m);
  }

  // Phase 2: Run with enabled=false
  console.log(`\n📊 Phase 2: Running with reflectionCycle.enabled = false`);
  setEnabled(projectRoot, false);
  delete require.cache[require.resolve(path.resolve(projectRoot, CONFIG_PATH))];
  delete require.cache[require.resolve('../core/reflection-cycle')];

  for (let i = 0; i < runs; i++) {
    console.log(`   Run ${i + 1}/${runs}...`);
    const m = await runSingleTest(projectRoot, 'disabled');
    results.disabled.push(m);
  }

  // Restore original config
  restoreConfig(projectRoot, originalConfig);
  delete require.cache[require.resolve(path.resolve(projectRoot, CONFIG_PATH))];
  console.log(`\n✅ Restored original config: reflectionCycle.enabled = ${originalEnabled}`);

  // Compute comparison
  const avg = (arr, key) => arr.length ? arr.reduce((s, m) => s + (m[key] ?? 0), 0) / arr.length : 0;
  const sum = (arr, key) => arr.reduce((s, m) => s + (m[key] ?? 0), 0);

  const enabledAvgDuration = avg(results.enabled, 'durationMs');
  const disabledAvgDuration = avg(results.disabled, 'durationMs');
  const enabledAvgActions = avg(results.enabled, 'actionsGenerated');
  const disabledAvgActions = avg(results.disabled, 'actionsGenerated');
  const enabledErrorRate = results.enabled.length ? sum(results.enabled, 'errorCount') / results.enabled.length : 0;
  const disabledErrorRate = results.disabled.length ? sum(results.disabled, 'errorCount') / results.disabled.length : 0;

  const durationDelta = disabledAvgDuration > 0 ? ((enabledAvgDuration - disabledAvgDuration) / disabledAvgDuration * 100) : 0;
  const actionDelta = disabledAvgActions > 0 ? ((enabledAvgActions - disabledAvgActions) / disabledAvgActions * 100) : 0;

  results.comparison = {
    avgDurationMs: { enabled: Math.round(enabledAvgDuration), disabled: Math.round(disabledAvgDuration), deltaPercent: Math.round(durationDelta * 100) / 100 },
    avgActions: { enabled: Math.round(enabledAvgActions * 100) / 100, disabled: Math.round(disabledAvgActions * 100) / 100, deltaPercent: Math.round(actionDelta * 100) / 100 },
    errorRate: { enabled: Math.round(enabledErrorRate * 100) / 100, disabled: Math.round(disabledErrorRate * 100) / 100 },
    convergenceRate: {
      enabled: results.enabled.filter(m => m.converged).length / Math.max(results.enabled.length, 1),
      disabled: results.disabled.filter(m => m.converged).length / Math.max(results.disabled.length, 1),
    },
  };

  return results;
}

function generateReport(results) {
  const c = results.comparison;
  const lines = [
    `# ReflectionCycle A/B Ablation Report`,
    ``,
    `| Metric | Enabled | Disabled | Delta |`,
    `|--------|---------|----------|-------|`,
    `| Avg Duration (ms) | ${c.avgDurationMs.enabled} | ${c.avgDurationMs.disabled} | ${c.avgDurationMs.deltaPercent}% |`,
    `| Avg Actions | ${c.avgActions.enabled} | ${c.avgActions.disabled} | ${c.avgActions.deltaPercent}% |`,
    `| Error Rate | ${c.errorRate.enabled} | ${c.errorRate.disabled} | - |`,
    `| Convergence Rate | ${(c.convergenceRate.enabled * 100).toFixed(0)}% | ${(c.convergenceRate.disabled * 100).toFixed(0)}% | - |`,
    ``,
    `## Verdict`,
    ``,
  ];

  const roiPositive = c.avgActions.deltaPercent > 0;
  const costAcceptable = c.avgDurationMs.deltaPercent < 50;

  if (roiPositive && costAcceptable) {
    lines.push(`✅ **ReflectionCycle provides net positive value**: +${c.avgActions.deltaPercent}% actions at ${c.avgDurationMs.deltaPercent}% duration cost.`);
  } else if (roiPositive && !costAcceptable) {
    lines.push(`⚠️ **ReflectionCycle has positive ROI but high latency cost**: +${c.avgActions.deltaPercent}% actions at ${c.avgDurationMs.deltaPercent}% duration overhead.`);
  } else {
    lines.push(`❌ **ReflectionCycle does not demonstrate clear value** in this test scenario.`);
  }

  lines.push(``, `## Raw Data`, ``, `### Enabled Runs`, ``);
  results.enabled.forEach((m, i) => {
    lines.push(`Run ${i + 1}: duration=${m.durationMs}ms, actions=${m.actionsGenerated}, converged=${m.converged}, errors=${m.errorCount}`);
  });
  lines.push(``, `### Disabled Runs`, ``);
  results.disabled.forEach((m, i) => {
    lines.push(`Run ${i + 1}: duration=${m.durationMs}ms, actions=${m.actionsGenerated}, converged=${m.converged}, errors=${m.errorCount}`);
  });

  return lines.join('\n');
}

async function main() {
  const args = process.argv.slice(2);
  const projectRoot = args.find(a => !a.startsWith('--')) || '.';
  const runsIdx = args.indexOf('--runs');
  const runs = runsIdx >= 0 ? parseInt(args[runsIdx + 1], 10) : DEFAULT_RUNS;
  const outputIdx = args.indexOf('--output');
  const outputPath = outputIdx >= 0 ? args[outputIdx + 1] : null;

  const results = await runAblationTest(projectRoot, runs);

  const report = generateReport(results);
  console.log(`\n${report}`);

  const jsonOutputPath = outputPath || path.join(projectRoot, 'output', 'reflection-cycle-baseline.json');
  const dir = path.dirname(jsonOutputPath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(jsonOutputPath, JSON.stringify(results, null, 2), 'utf-8');
  console.log(`\n📁 Results saved to: ${jsonOutputPath}`);

  const mdOutputPath = jsonOutputPath.replace('.json', '.md');
  fs.writeFileSync(mdOutputPath, report, 'utf-8');
  console.log(`📄 Report saved to: ${mdOutputPath}`);
}

main().catch(err => {
  console.error('AB test failed:', err);
  process.exit(1);
});
